package api

import "testing"

// Причина разбора показывается, только когда объясняет. «папка: INBOX»
// стояла у каждого письма и занимала строку, не сообщая ничего.
func TestEmptyReasonNotShown(t *testing.T) {
	пустые := []string{"папка: INBOX", "папка INBOX", "Папка: Входящие", "inbox", "по умолчанию", "  "}
	for _, r := range пустые {
		if !emptyReason(r) {
			t.Errorf("причина %q считается содержательной", r)
		}
	}
	живые := []string{"правило: отправитель в белом списке", "похоже на письмо из белого списка (сходство 91%)",
		"ящик в режиме «только читать»", "папка: Junk · перенесено правилом"}
	for _, r := range живые {
		if emptyReason(r) {
			t.Errorf("причина %q потерялась", r)
		}
	}
}
