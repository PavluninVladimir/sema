package api

import "testing"

// В шаге «Когда» три поля, и раньше сохранялось только одно: человек
// щёлкал по чипу «каждый час» или выбирал «запускать после задачи», а
// изменения молча не происходило. Форма, которая делает вид, что
// сохранила, — хуже формы, которая отказала.
func TestScheduleFromForm(t *testing.T) {
	случаи := []struct {
		что  string
		поля map[string]string
		ждём string
	}{
		{"только текст", map[string]string{"when": "каждые 15 мин"}, "каждые 15 мин"},
		{"щёлкнул по чипу", map[string]string{"preset": "каждый час", "when": ""}, "каждый час"},
		{"чип сильнее старого текста", map[string]string{"preset": "каждый час", "when": "9:00"}, "каждый час"},
		{"после задачи", map[string]string{"after": "Архив писем", "preset": "каждый час"}, "после «Архив писем»"},
		{"пункт «без очереди» не считается", map[string]string{"after": "— по времени, без очереди", "when": "9:00"}, "9:00"},
		{"ничего не выбрано", map[string]string{}, ""},
		{"пробелы не расписание", map[string]string{"when": "   "}, ""},
	}
	for _, c := range случаи {
		if got := scheduleFromForm(c.поля); got != c.ждём {
			t.Errorf("%s: вышло %q, ждали %q", c.что, got, c.ждём)
		}
	}
}
