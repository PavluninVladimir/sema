package api

// embedTrustRow — доверие эмбеддеру: вектор считается по содержимому
// письма, поэтому секретное недоверенному не отдаётся. Как у моделей —
// решение человека, а не адреса.
func embedTrustRow(s *Server) Component {
	row := Component{Type: "row", Layout: "wide", Subtitle: "Доверие эмбеддеру"}
	if s.eng.EmbedTrusted() {
		row.Caption = "доверенный — векторы считаются и по закрытым ящикам, и по секретному"
		row.Actions = []Action{{Action: "toggle_embed_trust", Label: "Считать внешним",
			Confirm: "Эмбеддер перестанет получать закрытые ящики и секретное: у таких писем не будет вектора и они выпадут из поиска по похожести.", ConfirmOK: "Считать внешним"}}
	} else {
		row.Caption = "внешний — закрытые ящики и секретное векторов не получают и в поиске по похожести не участвуют"
		row.Actions = []Action{{Action: "toggle_embed_trust", Label: "Доверять",
			Confirm: "Доверенный эмбеддер получит содержимое закрытых ящиков и секретного. Доверяйте только серверу на своём железе или в своей сети — адрес этого не гарантирует.", ConfirmOK: "Доверять"}}
	}
	return row
}
