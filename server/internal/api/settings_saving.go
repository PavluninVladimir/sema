package api

// Нижняя полоса сохранения настроек.
//
// Настройки правятся не по одной: человек открывает «Почту», меняет
// назначение ящика, глубину разбора и сроки хранения — это три разные
// формы, и у каждой была своя кнопка «Сохранить» внизу. Нажатая одна из
// трёх выглядела как «сохранено», хотя две других так и остались
// несохранёнными, и уход на соседнюю вкладку уносил их молча: ни счёта,
// ни вопроса, ни следа.
//
// Поэтому у экрана настроек одна полоса внизу: сколько правок не
// сохранено, «Сохранить» и «Отменить». Форму, которую она сохраняет,
// сервер помечает `Deferred`, и клиент не рисует у неё своей кнопки.
//
// Помечаются не все формы подряд. Форма, которая **заводит новое**
// (ящик, сервер, секрет, модель), свою кнопку оставляет: «Сохранить»
// внизу экрана ничего не говорит о том, что сейчас появится новый ящик,
// а пустая форма, в которую человек ничего не вписал, не должна попадать
// в счёт несохранённого. Отличаем по имени действия: в Сёме заведено
// `save_*`/`set_*` у правки существующего и `add_*`/`create_*` у
// создания — и `TestSettingsFormsSavedByBar` обходит все экраны
// настроек и следит, чтобы у каждой формы остался ровно один способ
// сохраниться.

import "strings"

// editsExisting — действие меняет то, что уже есть, а не заводит
// новое. Проверяется приставка, потому что имя действия в Сёме и есть
// его описание: `save_mail_modes` правит ящик, `add_host` заводит сервер.
func editsExisting(действие string) bool {
	return strings.HasPrefix(действие, "save_") || strings.HasPrefix(действие, "set_")
}

// savingBar — пометить формы экрана, которые сохраняет нижняя
// полоса. Форма с собственными кнопками кроме отправки остаётся как
// была: её вторая кнопка («Проверить», «Отклонить») ведёт своё действие,
// и без формы с `hx-post` ей неоткуда уйти на сервер.
func savingBar(cs []Component) {
	for i := range cs {
		savingBar(cs[i].Children)
		к := &cs[i]
		if к.Type != "form" || к.Submit == nil || len(к.Actions) > 0 {
			continue
		}
		if !editsExisting(к.Submit.Action) {
			continue
		}
		к.Deferred = true
	}
}
