package engine

import (
	"regexp"
	"strings"
	"unicode"
)

// Пустые итоги и общие места в память не идут. Сессия задачи «писем за
// сутки нет» и телеграм-чат из «привет — привет» дают модели повод
// написать «кристалл», а человек потом видит «Ждут вашего решения» из
// тринадцати строк ни о чём. Фильтр грубый и намеренно узкий: он режет
// только то, что явно ни о чём, остальное решает человек или разбор.

var reEmptyOutcome = regexp.MustCompile(`(?i)(писем|сообщений|новостей|событий|изменений|нового|важного|ничего)[^.]{0,40}(нет|не было|не найдено|не обнаружено|не нашлось|не поступало)|` +
	`(нет|не было|не найдено|не обнаружено)[^.]{0,30}(писем|сообщений|новостей|событий)|` +
	`(подтвержда|проверил|проверен)[^.]{0,30}(связ|готовност)|ответил[аи]? приветствием|согласил[ао]сь на дальнейшее общение|` +
	`тема (была )?закрыта после обсуждения`)

// emptyOutcome — запись говорит «ничего не произошло».
func emptyOutcome(text string) bool {
	return reEmptyOutcome.MatchString(strings.TrimSpace(text))
}

// genericLesson — совет ни о чём: без имени, числа, пути, кавычек или
// латиницы, короткий и в повелительном наклонении. «Закрывайте темы,
// когда обсуждение завершено» — это не урок из работы, это пословица.
func genericLesson(text string) bool {
	t := strings.TrimSpace(text)
	if len([]rune(t)) > 90 {
		return false
	}
	for _, r := range t {
		if unicode.IsDigit(r) || (r < 128 && unicode.IsLetter(r)) || r == '«' || r == '/' || r == '`' {
			return false
		}
	}
	low := strings.ToLower(t)
	for _, w := range []string{"всегда ", "регулярно ", "закрывайте ", "проверяйте ", "не забывайте ", "старайтесь ", "следует ", "нужно ", "важно "} {
		if strings.HasPrefix(low, w) {
			return true
		}
	}
	return false
}
