package engine

// След работы: что становится другим, когда работа сделана.
//
// 11–12 сентября 2026 разбор одного файла с QR-кодом крутился двое суток —
// 1187 обращений к модели по одному объекту, 9,2 млн токенов ответа и почти
// вся плата за DeepSeek. Ни ошибки, ни строки в журнале: каждый проход честно
// кончался успехом, и в журнале ровным шагом шло «разобран файл 413». Рядом
// шла вторая петля, дешевле: тридцать восемь картинок без текста
// перечитывались каждую минуту неделями.
//
// Приборы этого не видели и не могли: `-doctor` спрашивает «могу ли я
// встать», «Здоровье» — «сколько сейчас». Петля была здорова по каждому
// уровню: нагрузка 0.25, отказов нет, очередь не растёт. Она работала
// безупречно и впустую.
//
// Отсюда мера, одна на все проверки:
//
//	работа осмысленна, если после неё что-то стало другим
//
// Она же отличает петлю от нормы. Опрос почты повторяется вечно, и это не
// беда: у каждого его прохода есть след — сдвинутый курсор или новые письма.
// Различает не повтор, а след.
//
// След обязан быть дешёвым: это отпечаток тех полей объекта, которые работа
// меняет, а не пересказ объекта целиком. Виду работы, которому нечем ответить
// дёшево, положено сказать об этом прямо — `следаНет`. Молчание здесь
// недопустимо: молчащий вид выглядел бы как вид без петель.
//
// Реестр закрыт тестом на построение (`work_trace_test.go`): вид работы,
// появившийся в карте обработчиков и не объявивший следа, роняет сборку. Так
// уже сделано с парами «настройка — задача» и с дверью журнала настроек, и по
// той же причине: сторож, который знает про виды работ снаружи, отстанет от
// кода на первом же новом виде. Этим проект уже обжигался — «единственная
// дверь» mayGoOutside год стояла в коде, и не звал её никто.

import (
	"crypto/sha256"
	"encoding/hex"
	"strconv"
	"strings"
)

// workTrace — отпечаток того, что работа меняет у своего объекта. Пустая
// строка и false значат «следа нет»: либо объект пропал, либо вид работы
// дёшево ответить не может.
type workTrace func(ref string) (string, bool)

// noTrace — явный отказ вида работы от следа. Не то же самое, что забыть:
// забытый вид роняет сборку, отказавшийся виден в реестре.
func noTrace(string) (string, bool) { return "", false }

// traces — отпечаток на каждый вид работы очереди. Порядок тот же, что у карты
// обработчиков: их сверяет тест, и читать их удобнее рядом.
func (e *Engine) traces() map[string]workTrace {
	// у работы, которая правит объект на месте, след — отпечаток правимых
	// полей; у работы, которая добавляет записи, — их число
	byFields := func(table, key string, fields ...string) workTrace {
		return func(ref string) (string, bool) {
			id, err := strconv.ParseInt(strings.TrimSpace(ref), 10, 64)
			if err != nil {
				return "", false
			}
			return e.store.RowFingerprint(table, key, id, fields)
		}
	}
	byNumber := func(table, key string) workTrace {
		return func(ref string) (string, bool) {
			n, ok := e.store.RowCount(table, key, strings.TrimSpace(ref))
			if !ok {
				return "", false
			}
			return fingerprint(strconv.Itoa(n))
		}
	}

	return map[string]workTrace{
		// разбор файла пишет вид, продавца, сумму, сводку и сроки; длина
		// извлечённого текста — тоже он, её меняет перечитывание
		WorkFileParse: byFields("attachments", "id",
			"kind", "vendor", "amount", "currency", "summary", "doc_date", "due_date", "extracted"),
		// разбор памяти помечает запись разобранной и может завести новую версию
		WorkMemoryReview: byFields("memories", "id", "reviewed", "text", "supersedes"),
		// перевод кладёт строку в свою таблицу: работа добавляет, а не правит
		WorkTranslate: byNumber("message_translations", "message_id"),
		// разбор письма задним числом меняет состояние, причину и уверенность
		WorkMsgJudge: byFields("messages", "id", "status", "reason", "confidence"),
		// свёртка укорачивает сводку сессии
		WorkSessionFold: byFields("memory_sessions", "id", "summary"),
		// учёба кладёт черновик скилла
		WorkSkillLearn: byNumber("skill_drafts", "chat"),
	}
}

// Trace — отпечаток объекта для вида работы. Совпал до и после — работа
// ничего не изменила.
func (e *Engine) Trace(kind, ref string) (string, bool) {
	f, ok := e.traces()[kind]
	if !ok || f == nil {
		return "", false
	}
	return f(ref)
}

// fingerprint — короткая строка из частей. Лежит у каждой сделанной работы в
// очереди, поэтому длинной быть не должна.
func fingerprint(parts ...string) (string, bool) {
	h := sha256.Sum256([]byte(strings.Join(parts, "\x00")))
	return hex.EncodeToString(h[:8]), true
}
