package engine

// Пауза переподключения — одно правило на все живые соединения.
//
// Растущая пауза для того и растёт, чтобы не долбиться в закрытую дверь. Но
// она обязана где-то обнуляться, иначе измеряет не нынешнюю беду, а всю
// историю: у жителя машины этот урок записан в граблях с 11 сентября, а в
// MAX и Telegram его не применили. За 12 сентября пауза MAX дошла до потолка
// и держалась там, хотя связь жила по две минуты и была вполне рабочей.
//
// Правило живёт функцией, а не тремя строками внутри двух циклов: циклы
// нечем поднять в тесте, а решение проверить надо — и именно настоящее, а не
// его пересказ.

import "time"

const (
	pauseInitial = 5 * time.Second
	pauseCap     = 5 * time.Minute
	livedEnough  = time.Minute // столько прожив, соединение считается рабочим
)

// recountPause — сколько ждать перед следующей попыткой.
//
// Соединение, прожившее дольше порога, было рабочим: беда не тянется, а
// случилась только что, и мерить её всей прошлой историей неправильно.
func recountPause(pause, lived time.Duration) time.Duration {
	if lived > livedEnough {
		return pauseInitial
	}
	if pause < pauseCap {
		pause *= 2
	}
	if pause > pauseCap {
		pause = pauseCap
	}
	return pause
}
