package web

// Блок с файлами — единственная часть разметки, которую не проходил ни один
// тест. Обнаружилось это не догадкой: 27 сентября 2026 при переводе имён на
// латиницу каждое обращение шаблона обернули пометкой и **замерили**, какие
// исполняются. Из 870 мест исполнялось 721, и шаблон `files` не проходился
// целиком — то есть `IsImage`, `Path`, `ID`, `Name`, `Meta` держались только
// на внимательности того, кто правил.
//
// Опасность здесь не теоретическая: шаблон обращается к полям по имени, и
// компилятор этой связи не видит. Переименовали поле, забыли шаблон — сборка
// пройдёт, тесты промолчат, а человек увидит пустое место вместо вложения.
//
// Три ветки шаблона — три разных случая, и каждая называет своё поле:
// картинка идёт превью, файл с номером — ссылкой, файл без номера — просто
// подписью с путём в подсказке.

import (
	"strings"
	"testing"
)

func TestFilesBlockRendersAllThreeBranches(t *testing.T) {
	out, err := Render(Screen{Addr: "chat:1", Blocks: []Block{{
		Kind: "карточка-дела",
		Files: []File{
			{ID: 7, Name: "скан.jpg", IsImage: true},
			{ID: 8, Name: "счёт.pdf", Meta: "240 КБ"},
			{Name: "на этой машине.txt", Path: "/tmp/на этой машине.txt"},
		},
	}}})
	if err != nil {
		t.Fatal(err)
	}
	s := string(out)

	// картинка: превью и ссылка на байты по номеру
	for _, want := range []string{`class="preview"`, `src="/api/files/7"`, `alt="скан.jpg"`} {
		if !strings.Contains(s, want) {
			t.Errorf("картинка: в разметке нет %s", want)
		}
	}
	// файл с номером: ссылка, имя и мета
	for _, want := range []string{`href="/api/files/8"`, "счёт.pdf", "240 КБ"} {
		if !strings.Contains(s, want) {
			t.Errorf("файл: в разметке нет %s", want)
		}
	}
	// файл без номера: путь уходит в подсказку, а не в ссылку — байтов у
	// Сёмы нет, качать нечего
	if !strings.Contains(s, `title="/tmp/на этой машине.txt"`) {
		t.Errorf("файл без номера: путь не попал в подсказку:\n%s", s)
	}
	if strings.Contains(s, `href="/api/files/0"`) {
		t.Error("файл без номера нарисован ссылкой на нулевой номер")
	}
}
